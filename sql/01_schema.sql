-- Run as INVENTORY_APP. Oracle Database Free / XE supported.
CREATE TABLE branches (
    branch_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code VARCHAR2(12) NOT NULL UNIQUE,
    branch_name VARCHAR2(100) NOT NULL,
    city VARCHAR2(80) NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(40) NOT NULL UNIQUE,
    full_name VARCHAR2(100) NOT NULL,
    role_name VARCHAR2(20) NOT NULL CHECK (role_name IN ('ADMIN','MANAGER','CASHIER')),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N'))
);

CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(80) NOT NULL UNIQUE
);

CREATE TABLE suppliers (
    supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR2(120) NOT NULL,
    phone VARCHAR2(25),
    email VARCHAR2(120),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N'))
);

CREATE TABLE products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR2(30) NOT NULL UNIQUE,
    name VARCHAR2(150) NOT NULL,
    category_id NUMBER NOT NULL REFERENCES categories(category_id),
    supplier_id NUMBER REFERENCES suppliers(supplier_id),
    product_type VARCHAR2(15) DEFAULT 'STANDARD' NOT NULL CHECK (product_type IN ('STANDARD','PERISHABLE')),
    expiry_date DATE,
    unit_price NUMBER(12,2) NOT NULL CHECK (unit_price >= 0),
    reorder_level NUMBER(10) DEFAULT 5 NOT NULL CHECK (reorder_level >= 0),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_product_expiry CHECK (product_type = 'STANDARD' OR expiry_date IS NOT NULL)
);

CREATE TABLE inventory_stock (
    branch_id NUMBER NOT NULL REFERENCES branches(branch_id),
    product_id NUMBER NOT NULL REFERENCES products(product_id),
    quantity NUMBER(10) DEFAULT 0 NOT NULL CHECK (quantity >= 0),
    reorder_level NUMBER(10) DEFAULT 5 NOT NULL CHECK (reorder_level >= 0),
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_inventory_stock PRIMARY KEY (branch_id, product_id)
);

CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(120) NOT NULL,
    email VARCHAR2(150),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sales (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id NUMBER NOT NULL REFERENCES branches(branch_id),
    customer_id NUMBER REFERENCES customers(customer_id),
    status VARCHAR2(15) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','PROCESSING','COMPLETED','CANCELLED')),
    total_amount NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (total_amount >= 0),
    sold_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at TIMESTAMP
);

CREATE TABLE sale_items (
    sale_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id NUMBER NOT NULL REFERENCES sales(sale_id),
    product_id NUMBER NOT NULL REFERENCES products(product_id),
    quantity NUMBER(10) NOT NULL CHECK (quantity > 0),
    unit_price NUMBER(12,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE stock_movements (
    movement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id NUMBER NOT NULL REFERENCES branches(branch_id),
    product_id NUMBER NOT NULL REFERENCES products(product_id),
    movement_type VARCHAR2(20) NOT NULL CHECK (movement_type IN ('ADJUSTMENT','SALE','RETURN','TRANSFER_IN','TRANSFER_OUT','OPENING')),
    quantity_delta NUMBER(10) NOT NULL,
    reference_type VARCHAR2(30),
    reference_id NUMBER,
    note VARCHAR2(500),
    created_by NUMBER REFERENCES app_users(user_id),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE audit_log (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    actor VARCHAR2(100) DEFAULT USER NOT NULL,
    action_name VARCHAR2(40) NOT NULL,
    entity_name VARCHAR2(50) NOT NULL,
    entity_id NUMBER,
    details VARCHAR2(2000)
);

CREATE INDEX ix_stock_product ON inventory_stock(product_id);
CREATE INDEX ix_sales_sold_at ON sales(sold_at);
CREATE INDEX ix_sales_status ON sales(status);
CREATE INDEX ix_sale_items_sale ON sale_items(sale_id);
CREATE INDEX ix_movements_created ON stock_movements(created_at);
